-- V4 : lots d'import
-- Un dépôt de PDF forme un lot ; les fichiers sont traités en arrière-plan quand il y en a plusieurs.
-- Le récapitulatif (réussis, à compléter, en erreur) est consultable via GET /api/imports/{lot}.
-- Chaque fichier y a son résultat, y compris ceux qui n'ont rien enregistré (doublon, fichier invalide).

CREATE TABLE lot_import (
    id              uuid PRIMARY KEY,
    statut          varchar(40) NOT NULL,
    nombre_fichiers integer     NOT NULL,
    cree_par        bigint      NOT NULL REFERENCES utilisateur (id),
    cree_le         timestamptz NOT NULL DEFAULT now(),
    termine_le      timestamptz,
    CONSTRAINT ck_lot_import_statut CHECK (statut IN ('EN_COURS', 'TERMINE')),
    CONSTRAINT ck_lot_import_nombre CHECK (nombre_fichiers > 0),
    CONSTRAINT ck_lot_import_termine CHECK (statut <> 'TERMINE' OR termine_le IS NOT NULL)
);

CREATE INDEX ix_lot_import_cree_par ON lot_import (cree_par, cree_le);

CREATE TABLE resultat_lot_import (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id              uuid         NOT NULL REFERENCES lot_import (id) ON DELETE CASCADE,
    ordre               smallint     NOT NULL,
    nom_fichier         varchar(255) NOT NULL,
    issue               varchar(40)  NOT NULL,
    import_id           bigint REFERENCES import_fichier (id),
    rapport_id          bigint REFERENCES rapport_expertise (id),
    numero_rapport      varchar(30),
    statut_dossier      varchar(40),
    motif               text,
    controles_conformes smallint,
    controles_total     smallint,
    champs_a_saisir     smallint,
    traite_le           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_resultat_lot_ordre UNIQUE (lot_id, ordre),
    CONSTRAINT ck_resultat_lot_issue CHECK (issue IN ('ACCEPTE', 'RATTACHE_DOSSIER_EN_COURS', 'DOUBLON_FICHIER',
        'REFUSE_DOUBLON_NUMERO', 'REFUSE_GABARIT', 'ERREUR_LECTURE', 'FICHIER_INVALIDE', 'ERREUR')),
    CONSTRAINT ck_resultat_lot_statut CHECK (statut_dossier IN
        ('EN_COURS', 'IMPORTE', 'A_COMPLETER', 'A_VERIFIER', 'PRET_A_VALIDER', 'VALIDE', 'ARCHIVE'))
);

-- L'historique des imports regroupe les fichiers par lot
ALTER TABLE import_fichier
    ADD CONSTRAINT fk_import_fichier_lot FOREIGN KEY (lot_import) REFERENCES lot_import (id);
