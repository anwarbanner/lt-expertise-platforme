-- ---------------------------------------------------------------------
-- Utilisateurs (F11, P9)
-- ---------------------------------------------------------------------
CREATE TABLE utilisateur (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant         varchar(50)  NOT NULL,
    nom                 varchar(80)  NOT NULL,
    prenom              varchar(80)  NOT NULL,
    email               varchar(150),
    mot_de_passe_hash   varchar(100) NOT NULL,
    role                varchar(40)  NOT NULL,
    actif               boolean      NOT NULL DEFAULT true,
    tentatives_echouees smallint     NOT NULL DEFAULT 0,
    verrouille_jusqu_a  timestamptz,
    derniere_connexion  timestamptz,
    cree_le             timestamptz  NOT NULL DEFAULT now(),
    modifie_le          timestamptz  NOT NULL DEFAULT now(),
    version             integer      NOT NULL DEFAULT 0,
    CONSTRAINT uk_utilisateur_identifiant UNIQUE (identifiant),
    CONSTRAINT uk_utilisateur_email UNIQUE (email),
    CONSTRAINT ck_utilisateur_role CHECK (role IN ('ADMINISTRATEUR', 'GESTIONNAIRE', 'CONSULTATION')),
    CONSTRAINT ck_utilisateur_tentatives CHECK (tentatives_echouees >= 0)
);

-- ---------------------------------------------------------------------
-- Fichiers PDF importés, y compris refusés (F1, P1, P2)
-- Le PDF est stocké dans MinIO ; la base garde la référence et le hash.
-- ---------------------------------------------------------------------
CREATE TABLE import_fichier (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_fichier     varchar(255) NOT NULL,
    hash_sha256     varchar(64)  NOT NULL,
    taille_octets   bigint       NOT NULL,
    nombre_pages    smallint,
    bucket          varchar(63)  NOT NULL,
    cle_objet       varchar(500) NOT NULL,
    version_objet   varchar(100),
    type_mime       varchar(100) NOT NULL,
    gabarit_detecte varchar(40),
    statut_import   varchar(40)  NOT NULL,
    motif_refus     text,
    lot_import      uuid,
    importe_par     bigint       NOT NULL REFERENCES utilisateur (id),
    importe_le      timestamptz  NOT NULL DEFAULT now(),
    retraite_le     timestamptz,
    CONSTRAINT uk_import_fichier_hash UNIQUE (hash_sha256),
    CONSTRAINT uk_import_fichier_cle_objet UNIQUE (cle_objet),
    CONSTRAINT ck_import_fichier_hash CHECK (hash_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_import_fichier_taille CHECK (taille_octets > 0),
    CONSTRAINT ck_import_fichier_pages CHECK (nombre_pages IS NULL OR nombre_pages > 0),
    CONSTRAINT ck_import_fichier_type_mime CHECK (type_mime = 'application/pdf'),
    CONSTRAINT ck_import_fichier_statut CHECK (statut_import IN
        ('ACCEPTE', 'REFUSE_GABARIT', 'REFUSE_DOUBLON_NUMERO', 'ERREUR_LECTURE')),
    CONSTRAINT ck_import_fichier_motif CHECK (statut_import = 'ACCEPTE' OR motif_refus IS NOT NULL)
);

CREATE INDEX ix_import_fichier_importe_par ON import_fichier (importe_par);
CREATE INDEX ix_import_fichier_lot ON import_fichier (lot_import) WHERE lot_import IS NOT NULL;
CREATE INDEX ix_import_fichier_refuses ON import_fichier (importe_le) WHERE statut_import <> 'ACCEPTE';

-- ---------------------------------------------------------------------
-- Dossier : rapport d'expertise
-- ---------------------------------------------------------------------
CREATE TABLE rapport_expertise (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_rapport           varchar(30),
    nature_rapport           varchar(40)  NOT NULL DEFAULT 'DEFINITIF',
    type_procedure           varchar(40),
    statut                   varchar(40)  NOT NULL,
    cabinet                  varchar(100),
    expert                   varchar(100),
    compagnie                varchar(100),
    ref_sinistre             varchar(30),
    date_sinistre            date,
    date_mission             date,
    date_expertise           date,
    date_avant_reparation    date,
    date_en_cours_travaux    date,
    date_apres_travaux       date,
    date_rapport             date,
    lieu_rapport             varchar(60),
    nature_contrat           varchar(40),
    nature_evenement         varchar(40),
    zone_choc                smallint,
    reparateur               varchar(150),
    accord_reparateur        boolean,
    total_mo_ht              numeric(12, 2),
    total_mo_tva             numeric(12, 2),
    total_mo_ttc             numeric(12, 2),
    total_fournitures_ht     numeric(12, 2),
    total_fournitures_tva    numeric(12, 2),
    total_fournitures_ttc    numeric(12, 2),
    total_general_ht         numeric(12, 2),
    total_general_tva        numeric(12, 2),
    total_general_ttc        numeric(12, 2),
    vetuste_ttc              numeric(12, 2),
    depannage                numeric(12, 2),
    immobilisation           numeric(12, 2),
    type_reforme             varchar(40),
    epaviste_nom             varchar(100),
    epaviste_ville           varchar(60),
    valeur_neuf              numeric(12, 2),
    valeur_assuree           numeric(12, 2),
    valeur_venale            numeric(12, 2),
    valeur_epave             numeric(12, 2),
    tva_recuperable          boolean,
    montant_indemnisation    numeric(12, 2),
    montant_lettres          varchar(300),
    commentaire              text,
    gabarit_version          varchar(40),
    import_fichier_id        bigint REFERENCES import_fichier (id),
    valide_par               bigint REFERENCES utilisateur (id),
    valide_le                timestamptz,
    cree_le                  timestamptz  NOT NULL DEFAULT now(),
    cree_par                 varchar(50),
    modifie_le               timestamptz  NOT NULL DEFAULT now(),
    modifie_par              varchar(50),
    version                  integer      NOT NULL DEFAULT 0,

    -- P2 : un rapport, un dossier ; un PDF source pour un seul dossier
    CONSTRAINT uk_rapport_numero UNIQUE (numero_rapport),
    CONSTRAINT uk_rapport_import_fichier UNIQUE (import_fichier_id),

    CONSTRAINT ck_rapport_nature CHECK (nature_rapport IN ('DEFINITIF', 'NON_DEFINITIF', 'REFORME')),
    CONSTRAINT ck_rapport_procedure CHECK (type_procedure IN ('PROCEDURE_CLASSIQUE',
        'PRISE_EN_CHARGE_ET_PLUS_QUE_20000', 'PLUS_DE_20000', 'PRISE_EN_CHARGE', 'WAFA_24')),
    CONSTRAINT ck_rapport_statut CHECK (statut IN
        ('EN_COURS', 'IMPORTE', 'A_COMPLETER', 'A_VERIFIER', 'VALIDE', 'ARCHIVE')),
    CONSTRAINT ck_rapport_nature_contrat CHECK (nature_contrat IN ('RC', 'ASSURANCE_DOMMAGE')),
    CONSTRAINT ck_rapport_nature_evenement CHECK (nature_evenement IN
        ('CIRCULATION_HORS_STATIONNEMENT', 'STATIONNEMENT', 'AUTRE')),
    CONSTRAINT ck_rapport_type_reforme CHECK (type_reforme IN ('ECONOMIQUE', 'TECHNIQUE')),
    CONSTRAINT ck_rapport_zone_choc CHECK (zone_choc BETWEEN 1 AND 8),

    -- Seul un dossier « En cours » (repris du fichier Excel, F14) peut ne pas avoir de numéro
    CONSTRAINT ck_rapport_numero_obligatoire CHECK (statut = 'EN_COURS' OR numero_rapport IS NOT NULL),
    -- P3 : pas de statut VALIDE sans validation tracée (le rôle GESTIONNAIRE est vérifié côté application)
    CONSTRAINT ck_rapport_validation CHECK (statut <> 'VALIDE' OR (valide_par IS NOT NULL AND valide_le IS NOT NULL)),
    -- Un dossier validé ou archivé est complet sur les données qui fondent l'indemnisation
    CONSTRAINT ck_rapport_complet_si_valide CHECK (statut NOT IN ('VALIDE', 'ARCHIVE') OR (
        type_procedure IS NOT NULL AND tva_recuperable IS NOT NULL AND montant_indemnisation IS NOT NULL)),
    -- Un rapport non définitif ne peut pas être validé (choix par défaut du 22/10/2026)
    CONSTRAINT ck_rapport_non_definitif CHECK (nature_rapport <> 'NON_DEFINITIF' OR statut NOT IN ('VALIDE', 'ARCHIVE')),
    CONSTRAINT ck_rapport_reforme CHECK (type_reforme IS NULL OR nature_rapport = 'REFORME'),

    CONSTRAINT ck_rapport_montants_positifs CHECK (
        coalesce(total_mo_ht, 0) >= 0 AND coalesce(total_mo_tva, 0) >= 0 AND coalesce(total_mo_ttc, 0) >= 0
        AND coalesce(total_fournitures_ht, 0) >= 0 AND coalesce(total_fournitures_tva, 0) >= 0
        AND coalesce(total_fournitures_ttc, 0) >= 0
        AND coalesce(total_general_ht, 0) >= 0 AND coalesce(total_general_tva, 0) >= 0
        AND coalesce(total_general_ttc, 0) >= 0
        AND coalesce(vetuste_ttc, 0) >= 0 AND coalesce(depannage, 0) >= 0 AND coalesce(immobilisation, 0) >= 0
        AND coalesce(valeur_neuf, 0) >= 0 AND coalesce(valeur_assuree, 0) >= 0
        AND coalesce(valeur_venale, 0) >= 0 AND coalesce(valeur_epave, 0) >= 0
        AND coalesce(montant_indemnisation, 0) >= 0)
);

-- Recherche et filtres (F7), délais (F13)
CREATE INDEX ix_rapport_statut ON rapport_expertise (statut);
CREATE INDEX ix_rapport_type_procedure ON rapport_expertise (type_procedure);
CREATE INDEX ix_rapport_ref_sinistre ON rapport_expertise (ref_sinistre);
CREATE INDEX ix_rapport_date_rapport ON rapport_expertise (date_rapport);
CREATE INDEX ix_rapport_compagnie ON rapport_expertise (compagnie);
CREATE INDEX ix_rapport_expert ON rapport_expertise (expert);
CREATE INDEX ix_rapport_reparateur ON rapport_expertise (reparateur);
CREATE INDEX ix_rapport_zone_choc ON rapport_expertise (zone_choc);
CREATE INDEX ix_rapport_montant_indemnisation ON rapport_expertise (montant_indemnisation);
CREATE INDEX ix_rapport_valide_par ON rapport_expertise (valide_par);

-- ---------------------------------------------------------------------
-- Parties : assuré / adversaire
-- ---------------------------------------------------------------------
CREATE TABLE partie (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id       bigint      NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    type_partie      varchar(40) NOT NULL,
    nom_prenom       varchar(150),
    vehicule_libelle varchar(100),
    immatriculation  varchar(20),
    compagnie        varchar(100),
    numero_police    varchar(30),
    intermediaire    varchar(150),
    CONSTRAINT uk_partie_rapport_type UNIQUE (rapport_id, type_partie),
    CONSTRAINT ck_partie_type CHECK (type_partie IN ('ASSURE', 'ADVERSAIRE'))
);

CREATE INDEX ix_partie_immatriculation ON partie (immatriculation);

-- ---------------------------------------------------------------------
-- Véhicule expertisé : un par rapport
-- ---------------------------------------------------------------------
CREATE TABLE vehicule (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id                  bigint  NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    marque                      varchar(50),
    modele                      varchar(80),
    type_mine                   varchar(80),
    immatriculation             varchar(20),
    numero_serie                varchar(30),
    energie                     varchar(40),
    kilometrage                 integer,
    kilometrage_non_estimable   boolean NOT NULL DEFAULT false,
    puissance_fiscale           smallint,
    date_mise_circulation       date,
    etat_general                varchar(50),
    usure_pneu_avg              numeric(5, 2),
    usure_pneu_avd              numeric(5, 2),
    usure_pneu_arg              numeric(5, 2),
    usure_pneu_ard              numeric(5, 2),
    CONSTRAINT uk_vehicule_rapport UNIQUE (rapport_id),
    CONSTRAINT ck_vehicule_energie CHECK (energie IN ('ESSENCE', 'DIESEL', 'HYBRIDE', 'ELECTRIQUE', 'AUTRE')),
    CONSTRAINT ck_vehicule_kilometrage CHECK (kilometrage IS NULL OR kilometrage >= 0),
    CONSTRAINT ck_vehicule_puissance CHECK (puissance_fiscale IS NULL OR puissance_fiscale >= 0),
    CONSTRAINT ck_vehicule_usure CHECK (
        coalesce(usure_pneu_avg, 0) BETWEEN 0 AND 100 AND coalesce(usure_pneu_avd, 0) BETWEEN 0 AND 100
        AND coalesce(usure_pneu_arg, 0) BETWEEN 0 AND 100 AND coalesce(usure_pneu_ard, 0) BETWEEN 0 AND 100)
);

CREATE INDEX ix_vehicule_immatriculation ON vehicule (immatriculation);

-- ---------------------------------------------------------------------
-- Évaluation des dommages : 7 postes de main d'œuvre (page 1)
-- ---------------------------------------------------------------------
CREATE TABLE evaluation_main_oeuvre (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id    bigint      NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    poste         varchar(40) NOT NULL,
    nombre_heures numeric(7, 2),
    taux_horaire  numeric(12, 2),
    montant_ht    numeric(12, 2),
    montant_tva   numeric(12, 2),
    montant_ttc   numeric(12, 2),
    CONSTRAINT uk_evaluation_mo_rapport_poste UNIQUE (rapport_id, poste),
    CONSTRAINT ck_evaluation_mo_poste CHECK (poste IN ('MO_1_TOLERIE', 'MO_2_TOLERIE', 'MO_3_TOLERIE',
        'MO_PEINTURE', 'MO_1_MECANIQUE', 'MO_2_MECANIQUE', 'MO_3_MECANIQUE')),
    CONSTRAINT ck_evaluation_mo_positifs CHECK (
        coalesce(nombre_heures, 0) >= 0 AND coalesce(taux_horaire, 0) >= 0 AND coalesce(montant_ht, 0) >= 0
        AND coalesce(montant_tva, 0) >= 0 AND coalesce(montant_ttc, 0) >= 0)
);

-- ---------------------------------------------------------------------
-- Évaluation des dommages : 4 catégories de fournitures (page 1)
-- ---------------------------------------------------------------------
CREATE TABLE fourniture (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id  bigint      NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    categorie   varchar(40) NOT NULL,
    montant_ht  numeric(12, 2),
    montant_tva numeric(12, 2),
    montant_ttc numeric(12, 2),
    CONSTRAINT uk_fourniture_rapport_categorie UNIQUE (rapport_id, categorie),
    CONSTRAINT ck_fourniture_categorie CHECK (categorie IN
        ('PIECES', 'INGREDIENT_PEINTURE', 'PETITE_FOURNITURE', 'AUTRES')),
    CONSTRAINT ck_fourniture_positifs CHECK (
        coalesce(montant_ht, 0) >= 0 AND coalesce(montant_tva, 0) >= 0 AND coalesce(montant_ttc, 0) >= 0)
);

-- ---------------------------------------------------------------------
-- Détail fournitures / travaux (page 2), ligne par ligne
-- ---------------------------------------------------------------------
CREATE TABLE ligne_detail (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id        bigint       NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    ordre             smallint     NOT NULL,
    zone_libelle      varchar(60),
    zone_choc         smallint,
    famille           varchar(40),
    quantite          numeric(8, 2) NOT NULL,
    designation       varchar(150) NOT NULL,
    type_piece        varchar(40),
    prix_unitaire     numeric(12, 2),
    vetuste_pct       numeric(5, 2),
    tva_pct           numeric(5, 2),
    total_fourniture  numeric(12, 2),
    operation         varchar(40),
    nombre_heures     numeric(7, 2),
    tarif_horaire     numeric(12, 2),
    montant_mo_ttc    numeric(12, 2),
    CONSTRAINT uk_ligne_detail_rapport_ordre UNIQUE (rapport_id, ordre),
    CONSTRAINT ck_ligne_detail_ordre CHECK (ordre >= 0),
    CONSTRAINT ck_ligne_detail_zone_choc CHECK (zone_choc BETWEEN 1 AND 8),
    CONSTRAINT ck_ligne_detail_famille CHECK (famille IN ('TOLERIE', 'PEINTURE', 'MECANIQUE')),
    CONSTRAINT ck_ligne_detail_type_piece CHECK (type_piece IN ('ORIGINE', 'ADAPTABLE', 'REEMPLOI')),
    CONSTRAINT ck_ligne_detail_operation CHECK (operation IN ('ECHANGE', 'REPARATION')),
    CONSTRAINT ck_ligne_detail_quantite CHECK (quantite > 0),
    CONSTRAINT ck_ligne_detail_pourcentages CHECK (
        coalesce(vetuste_pct, 0) BETWEEN 0 AND 100 AND coalesce(tva_pct, 0) BETWEEN 0 AND 100),
    CONSTRAINT ck_ligne_detail_positifs CHECK (
        coalesce(prix_unitaire, 0) >= 0 AND coalesce(total_fourniture, 0) >= 0
        AND coalesce(nombre_heures, 0) >= 0 AND coalesce(tarif_horaire, 0) >= 0
        AND coalesce(montant_mo_ttc, 0) >= 0)
);

-- ---------------------------------------------------------------------
-- Valeurs clés extraites du commentaire de l'expert (F12, rapports 2026)
-- ---------------------------------------------------------------------
CREATE TABLE valeur_commentaire (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id     bigint      NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    cle            varchar(40) NOT NULL,
    valeur_texte   varchar(300),
    valeur_montant numeric(12, 2),
    valeur_date    date,
    CONSTRAINT uk_valeur_commentaire_rapport_cle UNIQUE (rapport_id, cle),
    CONSTRAINT ck_valeur_commentaire_cle CHECK (cle IN ('VALEUR_NEUF_CATALOGUE', 'VALEUR_VENALE_FMA',
        'MONTANT_DEVIS', 'ESTIMATION_SANS_DEVIS', 'CADRE_EXPERTISE', 'LOCALISATION_CHOC', 'EXPERT_CONFRERE',
        'MODE_EXPERTISE_CONFRERE', 'DATE_ACCORD', 'DIVERGENCE_USAGE')),
    CONSTRAINT ck_valeur_commentaire_renseignee CHECK (
        valeur_texte IS NOT NULL OR valeur_montant IS NOT NULL OR valeur_date IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- Résultats des contrôles de cohérence et champs manquants (F4, P4)
-- ---------------------------------------------------------------------
CREATE TABLE resultat_controle (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rapport_id      bigint       NOT NULL REFERENCES rapport_expertise (id) ON DELETE CASCADE,
    type            varchar(40)  NOT NULL,
    code            varchar(60)  NOT NULL,
    libelle         varchar(200) NOT NULL,
    champ           varchar(100),
    valeur_attendue numeric(12, 2),
    valeur_obtenue  numeric(12, 2),
    conforme        boolean      NOT NULL,
    execute_le      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_resultat_controle_type CHECK (type IN ('COHERENCE', 'CHAMP_MANQUANT'))
);

CREATE INDEX ix_resultat_controle_rapport ON resultat_controle (rapport_id);
CREATE INDEX ix_resultat_controle_anomalies ON resultat_controle (rapport_id) WHERE NOT conforme;

-- ---------------------------------------------------------------------
-- Journal d'audit (P7) : ajout seul
-- ---------------------------------------------------------------------
CREATE TABLE journal_audit (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horodatage              timestamptz NOT NULL DEFAULT now(),
    utilisateur_id          bigint REFERENCES utilisateur (id),
    identifiant_utilisateur varchar(50),
    action                  varchar(40) NOT NULL,
    type_entite             varchar(50),
    entite_id               bigint,
    rapport_id              bigint REFERENCES rapport_expertise (id),
    champ                   varchar(100),
    ancienne_valeur         text,
    nouvelle_valeur         text,
    details                 jsonb,
    adresse_ip              varchar(45),
    CONSTRAINT ck_journal_audit_action CHECK (action IN ('CONNEXION', 'ECHEC_CONNEXION', 'IMPORT',
        'IMPORT_REFUSE', 'CREATION', 'MODIFICATION', 'CHANGEMENT_STATUT', 'VALIDATION', 'ARCHIVAGE',
        'EXPORT_PDF', 'EXPORT_EXCEL', 'GESTION_UTILISATEUR'))
);

CREATE INDEX ix_journal_audit_horodatage ON journal_audit (horodatage);
CREATE INDEX ix_journal_audit_rapport ON journal_audit (rapport_id, horodatage) WHERE rapport_id IS NOT NULL;
CREATE INDEX ix_journal_audit_utilisateur ON journal_audit (utilisateur_id);

CREATE FUNCTION journal_audit_ajout_seul() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'journal_audit est en ajout seul (P7) : % interdit', TG_OP;
END;
$$;

CREATE TRIGGER trg_journal_audit_ajout_seul
    BEFORE UPDATE OR DELETE ON journal_audit
    FOR EACH ROW EXECUTE FUNCTION journal_audit_ajout_seul();

CREATE TRIGGER trg_journal_audit_pas_de_truncate
    BEFORE TRUNCATE ON journal_audit
    FOR EACH STATEMENT EXECUTE FUNCTION journal_audit_ajout_seul();
