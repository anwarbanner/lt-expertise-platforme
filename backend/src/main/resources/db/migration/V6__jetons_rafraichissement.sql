-- V6 : jetons de rafraîchissement (F11)
-- Jeton opaque remis dans un cookie HttpOnly ; seule son empreinte SHA-256 est stockée. Chaque usage le remplace
-- (rotation) ; il expire après une période d'inactivité et au plus tard à la fin de la session.

CREATE TABLE jeton_rafraichissement (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id   bigint      NOT NULL REFERENCES utilisateur (id),
    empreinte        varchar(64) NOT NULL,
    cree_le          timestamptz NOT NULL DEFAULT now(),
    expire_le        timestamptz NOT NULL,
    fin_session_le   timestamptz NOT NULL,
    revoque_le       timestamptz,
    CONSTRAINT uk_jeton_rafraichissement_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_jeton_rafraichissement_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_jeton_rafraichissement_expiration CHECK (expire_le <= fin_session_le)
);

CREATE INDEX ix_jeton_rafraichissement_utilisateur ON jeton_rafraichissement (utilisateur_id) WHERE revoque_le IS NULL;
